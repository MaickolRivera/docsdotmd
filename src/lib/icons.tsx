/** Nombre canónico de un icono (acepta alias y mayúsculas), o null si no existe. */
export function resolveIconName(name: string | null | undefined): IconName | null {
  if (!name) return null
  const key = name.trim().toLowerCase()
  if (Object.hasOwn(ICONS, key)) return key as IconName
  return ICON_ALIASES[key] ?? null
}

export function isIconName(name: string | null | undefined): name is IconName {
  return !!name && Object.hasOwn(ICONS, name)
}

/** Icono por nombre o alias; si no existe muestra `fallback`. */
export function DocIcon({
  name,
  className,
  fallback = "file-text",
}: {
  name: string | null | undefined
  className?: string
  fallback?: IconName
}) {
  const Icon = ICONS[resolveIconName(name) ?? fallback]
  return <Icon aria-hidden className={cn("size-4 shrink-0", className)} />
}
